/** Optional real-browser i18n acceptance test. Uses STUDIO_URL and PLAYWRIGHT_CORE. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_CORE || path.resolve(__dirname, '../frontend/node_modules/playwright'));
const url = process.env.STUDIO_URL || 'http://127.0.0.1:8000';
const screenshotDir = process.env.STUDIO_SCREENSHOT_DIR || '/tmp/studio-i18n-screenshots';
const semantic = graph => ({ ...graph, nodes: graph.nodes.map(({ position, ...node }) => node) });
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined, args: ['--no-sandbox'] });
  const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1680, height: 1050 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  const language = () => page.getByRole('combobox', { name: 'Language / 语言' }).filter({ visible: true });
  const check = name => console.log('PASS ' + name);
  fs.mkdirSync(screenshotDir, { recursive: true });
  try {
    await page.goto(url, { waitUntil: 'networkidle' });
    await page.getByText('Welcome to Legoizer', { exact: true }).waitFor();
    check('English first visit');
    await page.locator('.modal-backdrop').getByRole('combobox', { name: 'Language / 语言' }).selectOption('zh-CN');
    await page.getByText('欢迎使用 Legoizer', { exact: true }).waitFor();
    await page.getByRole('button', { name: /从零开始/ }).click();
    await page.getByRole('button', { name: '校验', exact: true }).click();
    await page.getByText('当前模型画布为空。', { exact: false }).first().waitFor();
    check('Chinese validation message, reason and fix');
    await language().selectOption('en');
    await page.getByText('The model canvas is empty.', { exact: false }).first().waitFor();
    check('Existing validation report switches without rerunning');
    await page.getByRole('button', { name: 'Templates', exact: true }).click();
    await page.getByRole('button').filter({ hasText: /^NAML\s*matching/ }).first().click();
    await page.waitForFunction(() => document.querySelectorAll('.react-flow__node').length > 5);
    await page.waitForTimeout(600);
    await page.locator('.tab-btn').filter({ hasText: 'Graph JSON' }).click();
    const original = JSON.parse(await page.locator('pre.code-view').innerText());
    assert.equal(original.template_id, 'naml');
    const compile = async name => {
      const response = page.waitForResponse(r => r.url().endsWith('/api/graph/compile') && r.request().method() === 'POST');
      await page.getByRole('button', { name, exact: true }).click();
      const result = await (await response).json();
      assert.ok(result.yaml_text && result.validation.valid);
      return result;
    };
    const enCompile = await compile('Generate Model');
    await language().selectOption('zh-CN');
    await page.getByRole('button', { name: '生成模型', exact: true }).waitFor();
    await page.waitForTimeout(600);
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
    await page.locator('.tab-btn').filter({ hasText: 'Graph JSON' }).click();
    const switched = JSON.parse(await page.locator('pre.code-view').innerText());
    assert.deepEqual(semantic(switched), semantic(original));
    check('Graph semantics and machine parameter keys preserved');
    const parameter = page.locator('.react-flow__node [data-param-name="hidden_size"]').first();
    assert.match(await parameter.innerText(), /隐藏维度/);
    assert.doesNotMatch(await parameter.innerText(), /hidden[_ ]size/);
    check('Chinese parameter labels have no raw key suffix');
    const zhCompile = await compile('生成模型');
    assert.equal(zhCompile.yaml_text, enCompile.yaml_text);
    assert.deepEqual(zhCompile.model_dict, enCompile.model_dict);
    check('Identical compiled YAML in both languages');
    await page.screenshot({ path: path.join(screenshotDir, 'zh-CN.png'), fullPage: true });
    const exitFocus = page.getByRole('button', { name: '退出聚焦', exact: true });
    if (await exitFocus.count()) await exitFocus.click();
    const search = page.getByRole('textbox', { name: '搜索组件', exact: true });
    await search.fill('注意力');
    assert.ok(await page.locator('.lib-item').count() > 0);
    await language().selectOption('en');
    assert.ok(await page.locator('.lib-item').count() > 0);
    await page.getByRole('textbox', { name: 'Search components', exact: true }).fill('item.cnn');
    assert.ok(await page.locator('.lib-item').count() > 0);
    check('Chinese, English and ID component search');
    await language().selectOption('zh-CN');
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
    assert.equal(await language().inputValue(), 'zh-CN');
    check('Language preference survives reload');
    await language().selectOption('en');
    await page.getByRole('button', { name: 'Generate Model', exact: true }).waitFor();
    await page.screenshot({ path: path.join(screenshotDir, 'en.png'), fullPage: true });
    assert.deepEqual(errors, []);
    check('No JavaScript exceptions');
    console.log('PASS all bilingual browser acceptance checks');
  } catch (error) { await page.screenshot({ path: path.join(screenshotDir, 'failure.png'), fullPage: true }); console.log((await page.locator('body').innerText()).slice(0, 6000)); throw error; } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
